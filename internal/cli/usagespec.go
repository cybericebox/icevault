package cli

import (
	"fmt"
	"io"
	"strings"
)

// The usage spec (KDL, https://usage.jdx.dev) of the command line, generated from the table of help.go: a mise file task that includes
// usage/icevault.usage.kdl completes the commands with it and checks the words of a command against it before the program starts. `icevault usage-spec` prints it; `mise run usage-spec` rewrites the committed file; a test fails when
// the file and the table differ.

// envComplete lists the environments of the project checkout (`icevault project envs`: the folders of its environments and plaintext trees).
const envComplete = `icevault project envs 2>/dev/null`

// kdlName is a name that has no quote or backslash in it (the table's names are words, flags and placeholders).
func kdlName(s string) string { return "\"" + s + "\"" }

func kdlString(s string) string { return "#\"" + s + "\"#" }

func kdlComplete(kind string, indent string) string {
	switch kind {
	case completeEnv:
		return fmt.Sprintf("%scomplete run=%s\n", indent, kdlString(envComplete))
	case completePath:
		return indent + "complete type=\"path\"\n"
	case completeDir:
		return indent + "complete type=\"dir\"\n"
	case completeNone:
		return indent + "complete type=\"none\"\n"
	}
	return ""
}

func kdlFlag(w io.Writer, f flagSpec, indent string, global bool) {
	decl := "--" + f.Name
	if f.Value != "" {
		decl += " <" + f.Value + ">"
	}
	extra := ""
	if global {
		extra = " global=#true"
	}
	fmt.Fprintf(w, "%sflag %s help=%s%s", indent, kdlName(decl), kdlString(f.Help), extra)
	if f.Value == "" {
		fmt.Fprint(w, "\n")
		return
	}
	fmt.Fprintf(w, " {\n%s  arg \"<%s>\" {\n%s", indent, f.Value, kdlComplete(f.Complete, indent+"    "))
	fmt.Fprintf(w, "%s  }\n%s}\n", indent, indent)
}

func kdlArg(w io.Writer, a argSpec, indent string) {
	decl := "<" + a.Name + ">"
	switch {
	case a.Rest:
		decl = "[-- " + a.Name + "]..."
	case a.Optional:
		decl = "[" + a.Name + "]"
	}
	help := a.Help
	if help == "" {
		help = "the " + a.Name
	}
	fmt.Fprintf(w, "%sarg %s help=%s", indent, kdlName(decl), kdlString(help))
	if c := kdlComplete(a.Complete, indent+"  "); c != "" {
		fmt.Fprintf(w, " {\n%s%s}\n", c, indent)
		return
	}
	fmt.Fprint(w, "\n")
}

// UsageSpec is the KDL of every command, in the order of the overview.
func UsageSpec() string {
	var b strings.Builder
	b.WriteString("// Generated by `icevault usage-spec` from internal/cli/help.go: do not edit; `mise run usage-spec` rewrites it.\n")
	kdlFlag(&b, flagSpec{Name: "vault", Value: phPath, Help: "the vault file (wins over ICEVAULT_VAULT)", Complete: completePath}, "", true)
	for _, name := range commandNames {
		s := specs[name]
		fmt.Fprintf(&b, "cmd %s help=%s", kdlName(name), kdlString(s.Summary))
		if len(s.Actions) > 0 {
			b.WriteString(" subcommand_required=#true")
		}
		b.WriteString(" {\n")
		for _, f := range s.Flags {
			kdlFlag(&b, f, "  ", len(s.Actions) > 0) // flags of a command with actions are given to its subcommands too
		}
		for _, a := range s.Args {
			kdlArg(&b, a, "  ")
		}
		for _, act := range s.Actions {
			fmt.Fprintf(&b, "  cmd %s help=%s", kdlName(act.Name), kdlString(act.Help))
			if len(act.Args) == 0 {
				b.WriteString("\n")
				continue
			}
			b.WriteString(" {\n")
			for _, a := range act.Args {
				kdlArg(&b, a, "    ")
			}
			b.WriteString("  }\n")
		}
		b.WriteString("}\n")
	}
	return b.String()
}
